/**
 * 说明文字不排在输入框下面、而是挂在标题后面的问号里：表单的每一行只有
 * 「标题 + 控件」两层，行高一致，报错时也不会把下面的内容顶下去。
 *
 * 必填在标题后面标一个系统红的星号，光靠颜色认不出来的人还有 `required` 那句。
 */
function FieldLabel({
  className,
  children,
  required,
  hint,
  ...props
}: React.ComponentProps<typeof Label> & {
  /** 必填：标题后面标一个红星号。 */
  required?: boolean
  /** 这个字段的说明，收在标题后面的问号里。 */
  hint?: React.ReactNode
}) {
  const text = useIntlayer("field")

  return (
    <Label
      data-slot="field-label"
      className={cn(
        "group/field-label peer/field-label flex w-fit gap-2 leading-snug group-data-[disabled=true]/field:opacity-50 has-data-checked:border-primary/30 has-data-checked:bg-primary/5 has-[>[data-slot=field]]:rounded-lg has-[>[data-slot=field]]:border has-[>[data-slot=field]]:not-has-[:disabled,[data-disabled]]:hover:bg-muted/50 has-[>[data-slot=field]]:has-[:focus-visible]:border-ring has-[>[data-slot=field]]:has-[:focus-visible]:ring-3 has-[>[data-slot=field]]:has-[:focus-visible]:ring-ring/50 *:data-[slot=field]:p-2.5 dark:has-data-checked:border-primary/20 dark:has-data-checked:bg-primary/10",
        "has-[>[data-slot=field]]:w-full has-[>[data-slot=field]]:flex-col",
        className
      )}
      {...props}
    >
      {children}
      {required && (
        <span data-slot="field-required" className="-ml-1 text-destructive">
          <span aria-hidden="true">*</span>
          <span className="sr-only">{text.required}</span>
        </span>
      )}
      {hint && (
        // 问号本身没有操作，手机上点它看提示。
        <Tooltip mobileTap>
          <TooltipTrigger
            // 表单里的按钮默认是提交按钮，问号不能把表单提交了。
            render={<button type="button" />}
            aria-label={text.hint.value}
            className="-m-1 inline-flex shrink-0 items-center justify-center rounded-full p-1 text-label-tertiary transition-colors duration-200 ease-apple outline-none hover:text-label-secondary focus-visible:ring-[3px] focus-visible:ring-ring/45 data-popup-open:text-label-secondary"
          >
            <CircleQuestionMarkIcon className="size-3.5" />
          </TooltipTrigger>
          {/* 手机上点开是居中 Dialog，标题给它当抬头。 */}
          <TooltipContent title={children}>{hint}</TooltipContent>
        </Tooltip>
      )}
    </Label>
  )
}

