/** 收起 / 展开前要多拖出的距离（px），免得在临界点来回跳。 */
const SIDEBAR_RESIZE_SNAP = 32;

/**
 * 可拖动的 SidebarRail：拖边缘改宽度，在最小、最大宽度之间；
 * 比最小宽度再往回拖 SIDEBAR_RESIZE_SNAP 就收起，收起时往外拖同样的距离就按最小宽度展开。
 * 不拖只点，照旧是展开 / 收起。松手时把宽度记进 cookie。
 */
function SidebarResizeRail({
  className,
  ...props
}: React.ComponentProps<"button">) {
  const { open, setOpen, toggleSidebar, widthRef, setWidth } = useSidebar();
  const dragRef = React.useRef<{
    /** 从这个点、这个宽度开始算；每次收起 / 展开后重新定起点。 */
    x: number;
    width: number;
    expanded: boolean;
    /** 左侧栏往右拖变宽，右侧栏反过来。 */
    direction: 1 | -1;
    wrapper: HTMLElement | null;
    moved: boolean;
  } | null>(null);
  // pointerup 之后浏览器还会派发 click，拖过的就不再当成点击。
  const suppressClickRef = React.useRef(false);

  const handlePointerDown = (event: React.PointerEvent<HTMLButtonElement>) => {
    if (event.button !== 0) return;
    event.currentTarget.setPointerCapture(event.pointerId);
    const side =
      event.currentTarget.closest<HTMLElement>("[data-side]")?.dataset.side;
    dragRef.current = {
      x: event.clientX,
      width: open ? widthRef.current : SIDEBAR_WIDTH_ICON_PX,
      expanded: open,
      direction: side === "right" ? -1 : 1,
      wrapper: event.currentTarget.closest<HTMLElement>(
        "[data-slot=sidebar-wrapper]",
      ),
      moved: false,
    };
  };

  const handlePointerMove = (event: React.PointerEvent<HTMLButtonElement>) => {
    const drag = dragRef.current;
    if (!drag) return;
    const offset = (event.clientX - drag.x) * drag.direction;
    if (!drag.moved) {
      if (Math.abs(offset) < 3) return;
      drag.moved = true;
      drag.wrapper?.setAttribute("data-resizing", "");
    }

    const next = drag.width + offset;
    if (drag.expanded) {
      if (next < SIDEBAR_MIN_WIDTH - SIDEBAR_RESIZE_SNAP) {
        setOpen(false);
        Object.assign(drag, {
          x: event.clientX,
          width: SIDEBAR_WIDTH_ICON_PX,
          expanded: false,
        });
      } else {
        setWidth(next);
      }
    } else if (next > SIDEBAR_WIDTH_ICON_PX + SIDEBAR_RESIZE_SNAP) {
      setWidth(SIDEBAR_MIN_WIDTH);
      setOpen(true);
      Object.assign(drag, {
        x: event.clientX,
        width: SIDEBAR_MIN_WIDTH,
        expanded: true,
      });
    }
  };

  const handlePointerEnd = () => {
    const drag = dragRef.current;
    dragRef.current = null;
    if (!drag?.moved) return;
    suppressClickRef.current = true;
    drag.wrapper?.removeAttribute("data-resizing");
    setWidth(widthRef.current, true);
  };

  return (
    <SidebarRail
      title="Drag to resize, click to toggle"
      onPointerDown={handlePointerDown}
      onPointerMove={handlePointerMove}
      onPointerUp={handlePointerEnd}
      onPointerCancel={handlePointerEnd}
      onClick={(event) => {
        event.preventDefault();
        if (suppressClickRef.current) {
          suppressClickRef.current = false;
          return;
        }
        toggleSidebar();
      }}
      // 外观和页面里的分栏拖动条（ResizableHandle withHandle）一致：中间常驻一个竖条把手，
      // 悬停不再显出整条细线，指针和 react-resizable-panels 在 Chrome / Firefox 下用的一样。
      className={cn(
        "touch-none items-center justify-center cursor-ew-resize! hover:after:bg-transparent",
        className,
      )}
      {...props}
    >
      <span aria-hidden className="z-10 h-6 w-1 shrink-0 rounded-lg bg-border" />
    </SidebarRail>
  );
}

